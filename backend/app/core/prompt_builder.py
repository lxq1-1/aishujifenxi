# ---- 用户 structure 的宽容解析 ----

# 兼容多种写法:
#   - 中文数字编号: 一、二、 三、 (一) 1) 1、 ①
#   - 阿拉伯编号:   1. 1、 1) (1)
#   - Markdown 标题: # / ## / ###
#   - 列表项:        - / *
#   - 纯标题(无任何前缀): "执行摘要" "执行摘要:"
#
# 解析后会:
#   1. 去掉以上前缀、冒号
#   2. 折叠多余空白
#   3. 去重(同名只保留首个)
#   4. 自动追加默认兜底章节(若一个都没识别出来)

# 编号前缀剥离正则:行首出现"一、" "1." "1、" "(1)" "①" 等编号、
# 或 Markdown 标题 "## "、列表项 "- " 时,把这些前缀吃掉;
# 末尾的冒号是**可选**的(老版本必须以冒号结尾才能匹配,导致用户填的
# "一、执行摘要" 这种不带冒号的章节无法剥前缀,整条前缀都进了 sections 的 key,
# 让 LLM 直接输出 {"一、执行摘要": "..."} 或干脆忽略清单自创 "overview" 章节)。
_TITLE_PREFIX_RE = re.compile(
    r"""^\s*
        (?:
            # 中文/数字/带圈编号 + 括号包裹的编号(如"(1)" "[1]" "(一)")
            (?:[（(\[【]?\s*(?:[一二三四五六七八九十百千]+|[0-9]+|[①-⑳])\s*[)）\]】]?)\s*[、,.\)::]\s*
          | [##]+\s+
          | [-*]\s+
        )?
        (?P<title>.*?)
        \s*$
    """,
    re.VERBOSE,
)

# 单独用于"行末冒号剥离"的正则(与前缀剥离解耦):
# 即使前缀没匹配上,这里也会把行尾的中英文冒号干掉,避免传给 LLM 的章节
# 清单里残留 "执行摘要:" 这种尾巴。
_TRAILING_COLON_RE = re.compile(r"\s*[::]\s*$")


# 已知前缀的"剥一遍"正则:作为 _TITLE_PREFIX_RE 失配时的兜底,
# 防止用户填 "一、执行摘要" 这种末尾不带冒号的章节被原样当作标题。
# 注意:这里只剥前缀、不动尾部,避免误伤合法标题(如 "(一) 战略目标 (草案)")。
_KNOWN_PREFIX_RE = re.compile(
    r"""^\s*
        (?:
            # 中文数字编号 "一、" "二十、";阿拉伯 "1." "12,";带圈 "①";
            # 括号 "(1)" "(一)" "[1]" 这种 —— 但**只在前缀位置**剥,不在标题中间剥
            (?:[（(\[【]?\s*(?:[一二三四五六七八九十百千]+|[0-9]+|[①-⑳])\s*[)）\]】]?)\s*[、,.\)::]\s*
          | # Markdown 标题
            [##]+\s+
          | # 列表项
            [-*]\s+
        )
        (?P<rest>.+)$
    """,
    re.VERBOSE,
)


def _strip_known_prefix(line: str) -> str:
    """从行首剥掉已知编号/列表前缀;剥不动时原样返回。

    用途:_TITLE_PREFIX_RE 因尾部不带冒号而不匹配时的兜底路径,
    保证用户填 "一、执行摘要" 也能正确得到 "执行摘要"。
    边界保护:若剥完后 `rest` 是空(用户只填了 "一、"),则原样返回,
    让外层"长度/句号"检查继续生效而不是产生空标题。
    """
    if not line:
        return line
    m = _KNOWN_PREFIX_RE.match(line)
    if not m:
        return line.strip()
    rest = (m.group("rest") or "").strip()
    return rest if rest else line.strip()


def _parse_section_titles(structure: str) -> list[str]:
    """从用户填写的 structure 文本里抽取出章节标题列表。

    解析策略(宽容,逐行匹配):
        - 识别中文/阿拉伯编号(常见"一、" "1." "1、" "(一)" "①")
        - Markdown 标题 "# ... / ## ..." 自动作为章节
        - 列表项 "- ... / * ..." 自动作为章节
        - 普通行(无前缀)只要看起来像标题(短、非空、无句号)也算
        - 空行跳过
        - 行内有明显描述文字(过长、含多个句号)视为该章节的"补充说明",不作为独立章节

    Args:
        structure: 用户在前端填写的"报告结构"Markdown 文本,可能为空。

    Returns:
        章节标题列表(已去重、去前缀)。如果一个都没识别出来,
        返回内置的兜底 4 段骨架,保证总能传给 LLM 一组可用章节名。
    """
    if not structure:
        return _DEFAULT_FALLBACK_TITLES.copy()

    titles: list[str] = []
    seen: set[str] = set()
    for raw in structure.splitlines():
        line = raw.strip()
        if not line:
            continue
        # 跳过空行/纯分隔线
        if not line or set(line) <= {"-", "=", "*", "#", "~"}:
            continue

        # 至少看起来像"标题":优先匹配带前缀的;
        # 解析后非空才采纳;空标题(纯分隔符)丢弃。
        m = _TITLE_PREFIX_RE.match(line)
        if m and m.group("title"):
            title = (m.group("title") or "").strip()
        else:
            # 【修复】正则没匹配上时,再走一遍独立的前缀剥离:
            # 用户最常见的写法是 "一、执行摘要"(末尾无冒号),
            # 正则匹配不上时这里手工剥掉中文/数字编号、Markdown 标题、列表项前缀,
            # 否则整条前缀会被当成标题一起传给 LLM,导致 sections 的 key
            # 变成 "一、执行摘要" 这种脏字符串,前端不得不再次 strip 才能显示。
            title = _strip_known_prefix(line)

        # 去掉行尾的中英文冒号(与前缀剥离解耦,即使上面正则没匹配上也能剥掉)
        title = _TRAILING_COLON_RE.sub("", title).strip()
        title = title.rstrip(":").rstrip(":").strip()
        # 去掉形如 "—— 说明" 的尾随说明,只保留标题主体
        for sep in (" —— ", " -- ", " — ", " - "):
            if sep in title:
                title = title.split(sep, 1)[0].strip()
                break
        # 去掉尾部 (xxx) 备注
        title = re.sub(r"[\s(（][^()（）]{2,30}[)）]\s*$", "", title).strip()

        if not title:
            continue
        # 太长(>60 字)或带太多句号:当成说明文字,跳过
        if len(title) > 60 or title.count("。") + title.count(".") >= 2:
            continue

        if title not in seen:
            seen.add(title)
            titles.append(title)

    return titles or _DEFAULT_FALLBACK_TITLES.copy()


# 当用户没填结构、或全无可识别章节时,使用的兜底 4 段标题。
# 注意:这些标题可读、与 _DEFAULT_TEMPLATE 兼容。
_DEFAULT_FALLBACK_TITLES: list[str] = [
    "执行摘要",
    "关键指标分析",
    "问题与归因",
    "下一步建议",
]


def _render_template(category: str, structure: str) -> str:
    """根据分类取出骨架,填入用户自定义的章节结构。"""
    tpl = _CATEGORY_TEMPLATES.get(category) or _DEFAULT_TEMPLATE

    # 把用户填的章节解析为有序列表,渲染为"章节清单",作为硬约束。
    titles = _parse_section_titles(structure)
    if titles:
        structure_text = "\n".join(f"- {i + 1}. {t}" for i, t in enumerate(titles))
        structure_block = f"【章节清单(必须严格按此输出 sections 的键)】\n{structure_text}"
    else:
        structure_block = "【章节清单(必须严格按此输出 sections 的键)】\n- 1. (无,使用通用章节)"

    rendered_hint = tpl["section_hint"].replace("{structure}", structure_block)
    # 【每节一图】可视化要求,在 section_hint 末尾追加,
    # 让 LLM 在【本期真实数据】允许的前提下,为每个有数据的章节配图并填到 chart_option.by_section。
    return f"{tpl['role']}\n\n{rendered_hint}{_VISUALIZATION_HINT}"


def _indicators_to_text(indicators: dict[str, Any]) -> str:
    """指标 JSON → 文本片段,截断防止超 token。"""
    return json.dumps(indicators or {}, ensure_ascii=False, indent=2, default=json_default)[:12000]


# ==================== KPI 宽表写作指引(2026-10 新增)====================
# 背景:
#     年报里最有价值的数据是"指标 × 目标/实际/达成率/同比"这种 KPI 宽表,
#     2026-10 起 pandas_engine 会把它识别成 indicators.kpi_matrix.records,
#     结构形如:
#         [{"指标":"销售额","单位":"万元","目标":5000.0,"实际":4680.0,
#           "去年同期":4200.0,"达成率":0.936,"同比":0.114,
#           "达成率%":93.6,"同比%":11.43}, ...]
#     旧 Prompt 里**没有任何**关于"怎么引用这些字段"的说明,LLM 不知道
#     「达成率%」和「达成率」的区别,也不知道有「单位」字段可用,
#     于是写出一堆"整体经营处于收入低速增长、利润承压的剪刀差区间"
#     这种零数字的定性废话 —— 这正是用户看到的"报告只有文字"。
#     所以这里补一段显式写作指令,告诉 LLM 逐指标、逐数字地写。
_KPI_WRITING_GUIDE = (
    "\n【KPI 明细表 · 必须逐条引用的真实数据】\n"
    "  【本期真实数据】里的 `kpi_matrix`(或 `kpi_matrix_by_sheet`)是本报告**最核心的数据**,"
    "它已经把每个指标的目标/实际/达成率/同比都算好了。写作硬规则:\n"
    "  1. **必须点名指标**:写「销售额达成率 93.6%」「新客户数 1350 个,超额 12.5%」,\n"
    "     **严禁**写「收入板块稳步增长」「整体表现尚可」这类不点名的概括;\n"
    "  2. **数字 + 单位成对出现**:记录里有「单位」字段(万元/单/元/%/个),\n"
    "     引用金额类指标必须带单位(如「4680 万元」),比率类用「达成率%」「同比%」字段;\n"
    "  3. **达成/未达成必须点出方向**:达成率 ≥ 100% 写「超额完成 X%」,\n"
    "     < 100% 写「缺口 X%」;新客户数 112.5% 这类超额要单独点出是亮点;\n"
    "  4. **同比必须给数值**:有「同比%」的指标要写出具体涨跌幅(如「同比 +11.43%」),\n"
    "     不要只说「同比增长」;\n"
    "  5. **算缺口**:目标与实际的差值、缺口百分比,是管理层最关心的信息,\n"
    "     请主动计算并写出(如「销售额缺口 320 万元,完成率 93.6%」);\n"
    "  6. **不要跨指标求和**:不同指标量纲不同(万元/单/%)，严禁把它们的值相加或\n"
    "     取平均 —— 那样算出来的数字毫无业务意义(这是最常见的错误)。\n"
)


def _render_kpi_guide(indicators: dict[str, Any]) -> str:
    """仅当 indicators 里确实有 KPI 宽表时,才返回 KPI 写作指引段。

    没有 KPI 数据时返回空串(让上层 filter 掉),避免给纯明细表场景
    加一段无关的指令、干扰 LLM。
    """
    kpi = indicators.get("kpi_matrix")
    if not (isinstance(kpi, dict) and kpi.get("records")):
        by_sheet = indicators.get("kpi_matrix_by_sheet")
        if not (isinstance(by_sheet, dict) and by_sheet):
            return ""
    return _KPI_WRITING_GUIDE


def _fmt_whitelist_num(v: Any) -> str:
    """白名单里的数值格式化:去掉无意义的 ".0" 尾巴。

    白名单是模型写数字时的**直接抄写源**,如果这里写 "4680.0",
    模型大概率会原样抄成 "4680.0 万元",报告里就带着一堆
    程序 dump 味十足的浮点数。源头清洗比事后纠正有效得多。
    """
    if isinstance(v, bool) or not isinstance(v, (int, float)):
        return str(v)
    f = float(v)
    if f == int(f) and abs(f) < 1e15:
        return str(int(f))
    return str(round(f, 4)).rstrip("0").rstrip(".")


def _render_whitelist(indicators: dict[str, Any]) -> str:
    """生成【可用数字白名单】:把本次数据里真实存在的数值列成清单。

    【2026-10 新增,实测必要】
        修完数据层后指标已经是真数据了,但实测 deepseek-flash 仍会编正文数字:
            「成本与盈利能力」章写"本期毛利率31.2%、同比-1.8个百分点、
              期间费用率18.4%、销售费用率8.2%…" —— 逐个核数,16 个数字里
              13 个在源数据中找不到(真实毛利率是 33.8%,源数据里根本没有
              "费用率"这个字段,也没有"A线"这个业务线)。
        根因是"严禁编造"这类**禁令**对小模型约束力有限 ——
        它不知道哪些数字可用,只能凭业务常识编出看起来合理的值。
        改成**白名单**后效果完全不同:正面告诉它"只能从这些数字里选",
        编造的空间被物理限制住了。

    清单来源(全部是真实数据,不含任何推断值):
        - KPI 记录的 目标/实际/去年同期/达成率%/同比%
        - 周期趋势的 各期值/总计/均值/峰值/谷值
        - 分组聚合的 name/value
        - 数值列的 sum/mean/max/min/median
    """
    if not isinstance(indicators, dict):
        return ""

    lines: list[str] = []

    # ---- KPI 明细 ----
    kpi = indicators.get("kpi_matrix")
    if not (isinstance(kpi, dict) and kpi.get("records")):
        for v in (indicators.get("kpi_matrix_by_sheet") or {}).values():
            if isinstance(v, dict) and v.get("records"):
                kpi = v
                break
    records = (kpi or {}).get("records") or [] if isinstance(kpi, dict) else []
    if records:
        lines.append("  【KPI 指标可用数值】(格式:指标 目标/实际/达成率/同比)")
        for r in records[:12]:
            nm = r.get("指标")
            if not nm:
                continue
            unit = r.get("单位")
            suf = f" {unit}" if unit and unit != "%" else ""
            # 比率类指标(单位 %)统一按百分数展示:目标是 0.35 就写 35%,
            # 否则模型会照抄 0.35 并自己推算,极易产生精度错误
            ratio_like = (unit == "%")

            def _v(key: str) -> str:
                v = r.get(key)
                if not isinstance(v, (int, float)) or isinstance(v, bool):
                    return ""
                if ratio_like:
                    return f"{round(float(v) * 100, 2)}%"
                return f"{_fmt_whitelist_num(v)}{suf}"

            bits = []
            t_txt = _v("目标")
            if t_txt:
                bits.append(f"目标 {t_txt}")
            a_txt = _v("实际")
            if a_txt:
                bits.append(f"实际 {a_txt}")
            ly_txt = _v("去年同期")
            if ly_txt:
                bits.append(f"去年同期 {ly_txt}")
            if isinstance(r.get("达成率%"), (int, float)):
                bits.append(f"达成率 {r['达成率%']}%")
            if isinstance(r.get("同比%"), (int, float)):
                bits.append(f"同比 {r['同比%']}%")
            if bits:
                lines.append(f"    - {nm}: " + "、".join(bits))

    # ---- 周期趋势 ----
    for key, tr in (indicators.get("trend") or {}).items():
        if not isinstance(tr, dict) or not tr.get("x"):
            continue
        xs, ys = tr.get("x") or [], tr.get("y") or []
        pairs = "、".join(
            f"{x}={_fmt_whitelist_num(y)}"
            for x, y in list(zip(xs, ys))[:14]
        )
        extra = []
        if isinstance(tr.get("总计"), (int, float)):
            extra.append(f"合计 {_fmt_whitelist_num(tr['总计'])}")
        peak, trough = tr.get("峰值"), tr.get("谷值")
        if isinstance(peak, dict):
            extra.append(
                f"最高 {peak.get('周期')}({_fmt_whitelist_num(peak.get('值'))})")
        if isinstance(trough, dict):
            extra.append(
                f"最低 {trough.get('周期')}({_fmt_whitelist_num(trough.get('值'))})")
        lines.append(f"  【周期走势可用数值】{key}")
        lines.append(f"    - 各期: {pairs}")
        if extra:
            lines.append("    - " + "、".join(extra))
        break  # 只列第一条趋势,避免清单过长

    # ---- 分组聚合 ----
    for key, items in (indicators.get("by_group") or {}).items():
        if not isinstance(items, list) or not items:
            continue
        pairs = "、".join(
            f"{it.get('name')}={_fmt_whitelist_num(it.get('value'))}"
            for it in items[:8] if isinstance(it, dict)
        )
        if pairs:
            lines.append(f"  【分组构成可用数值】{key}")
            lines.append(f"    - {pairs}")
        break

    # ---- 数值列统计 ----
    ns = indicators.get("numeric_summary") or {}
    if ns:
        stat_bits = []
        for col, agg in list(ns.items())[:6]:
            if not isinstance(agg, dict):
                continue
            s = agg.get("sum")
            if isinstance(s, (int, float)):
                stat_bits.append(f"{col} 合计={_fmt_whitelist_num(s)}")
        if stat_bits:
            lines.append("  【数值列合计可用数值】")
            lines.append("    - " + "、".join(stat_bits))

    if not lines:
        return ""

    return (
        "\n【可用数字白名单 · 极其重要】\n"
        "  下列数字是本期数据中**真实存在**的全部可用数值。"
        "你在正文里引用的每一个数字,**必须**来自这份白名单,"
        "白名单里没有的数字一律不许写(哪怕它看起来再合理、再说得通)。\n"
        + "\n".join(lines) + "\n"
        "  特别提醒:\n"
        "  - 源数据里**没有**的字段(如费用率、现金流科目、人力成本等)**不得杜撰**。\n"
        "    如果某章节想分析的维度白名单里没有,就**改用白名单里已有的维度**\n"
        "    做分析(如没有费用率数据,就从毛利率、客单价、达成率去分析盈利质量),\n"
        "    而**不是**写「本期数据未覆盖该明细数据」这类占位话术交白卷;\n"
        "  - 不得自行计算白名单里没有的派生指标(如「投入产出比」「费用率偏差」\n"
        "    「结构占比提升 X 个百分点」这类需要额外假设才能算出的量);\n"
        "  - 不得虚构不存在的业务实体(如「A 线产品」「B 渠道」)作为归因对象。\n"
    )


def build_user_prompt(
    category: str,
    structure: str,
    indicators: dict[str, Any],
    reference: str = "",
    template_description: str = "",
    analysis_intent: str = "",
    feedback: str = "",
    sheets: list[dict[str, Any]] | None = None,
) -> str:
    """把分类骨架 + 用户章节结构 + 注入的指标/参考数据合并为最终 user 消息。

    入参:
        category:    模板分类(年度/季度/述职/简报/销售/...);未知分类走通用骨架。
        structure:   用户在前端填写的"报告结构"Markdown(章节标题列表)。
        indicators:  Pandas 指标 dict,会被 JSON 化后注入 {{indicators}}。
        reference:    业务资料文本(RAG 预留),会被注入 {{reference}};空时填占位文案。
        template_description: 用户/内置在模板上填写的「业务背景/口径说明」,
                     会被注入为【模板业务背景】段。空字符串时该段被省略。
        analysis_intent: 用户在「开始 AI 分析」前临时输入的分析重点(自由长度);
                     非空时插入到「【模板业务背景】」之后、输出 schema 之前的「【本次分析重点】」段。
        feedback:    用户在报告页对已生成报告提的修改意见(自由长度);
                     非空时插入到「【本次分析重点】」之后、输出 schema 之前的「【用户修改意见】」段。
        sheets:      数据集的工作表明细 `[{name, rows, cols}, ...]`。
                     仅当 `len(sheets) > 1` 时,会在【本期真实数据】之前插入【数据来源】小节,
                     引导 LLM 主动引用各 sheet 的数字(否则不插入,行为兼容旧)。

    返回:
        可直接喂给 llm.chat / llm.chat_json 的 user 消息。
    """
    body = _render_template(category, structure)
    indicator_text = _indicators_to_text(indicators)
    reference = (reference or "").strip() or "（本期无业务资料,RAG 预留）"

    # 用户填的模板描述作为「业务背景」段落,可影响 LLM 的语气、关注点与口径;
    # 空时省略该段,避免无意义标记。限定最大长度防止 prompt 过大。
    desc = (template_description or "").strip()[:2000]
    background_part = (
        f"【模板业务背景】\n{desc}\n(请将上述背景作为口径/受众/语气偏好,贯穿整份报告;与【本期真实数据】冲突时以指标为准。)"
        if desc else ""
    )

    # 用户本次分析时临时输入的"分析重点" —— 作为本次任务的优先级指令,
    # 位置在模板业务背景之后、输出 schema 之前。
    # 这样"模板描述"作为公司口径基准先被 LLM 接收,"本次重点"作为临时优先级追加在后面。
    intent = (analysis_intent or "").strip()
    intent_part = (
        f"【本次分析重点】\n{intent}\n(用户本次分析时关注的重点如下,请在全文"
        "(尤其是「关键指标」「问题」「建议」相关章节)中**主动体现**这些关注点;"
        "**主动略过**用户明确不看的内容;不得编造指标未给出的内容。)"
        if intent else ""
    )

    # 用户对已生成报告提的"修改意见" —— 位置在 analysis_intent 之后(若存在)、输出 schema 之前。
    # 用于"基于意见重写报告"的迭代场景:让 LLM 在保留数据事实与口径的前提下,主动回应这些意见。
    fb = (feedback or "").strip()
    feedback_part = (
        f"【用户修改意见】\n{fb}\n(用户希望基于已有报告调整,重点如下。"
        "请在保留原报告数据事实与口径的同时,主动回应以下意见:能改就改,该删就删,该改语气就改语气;"
        "不允许编造原指标未给出的数字;若与某条意见冲突导致无法两全,"
        "**优先**遵循用户意见并在摘要中说明取舍。)"
        if fb else ""
    )

    # 【数据来源】段 —— 仅当 Excel 含 ≥2 张 sheet 时插入。
    # 位置:业务背景/本次重点/用户意见 之后、【本期真实数据】之前。
    # 目的:让 LLM 明确知道"指标数据"是跨多张 sheet 汇总的,从而在写
    # "业务结构/渠道分析/产品分析/目标达成"等章节时主动引用各 sheet 的数字,
    # 而不是只盯着首个 sheet 的明细数据。
    sheets_part = _render_sheet_source(sheets)

    # 【2026-10 新增】KPI 写作指引:仅当 indicators 含 KPI 宽表时插入。
    # 位置紧贴【本期真实数据】之前 —— 让 LLM 读完写作规则后紧接着看到数据,
    # 规则与数据的距离越近,遵守率越高(实测把规则放在最前面容易被长
    # 上下文稀释,尤其 deepseek-flash 这类小模型)。
    kpi_guide_part = _render_kpi_guide(indicators or {})
    # 【2026-10 新增】可用数字白名单。
    # 放在【本期真实数据】**紧前面** —— 模型读白名单在先、读原始 JSON 在后,
    # 白名单会成为它写数字时的首选来源。放最后会被长 JSON 稀释掉。
    whitelist_part = _render_whitelist(indicators or {})

    # 【2026-10 新增】极简任务概要:把「要写哪几章」压缩成百来字,
    # 放在数据**之前**。
    # 为什么需要:数据提到最前解决了"模型没看到数据"的问题,
    # 但实测 MiniMax 随后返回了 `"sections": {}`(空章节)——
    # 因为章节清单被挤到了 9000 字符之后,模型写正文时已经想不起要写哪几章。
    # 这里用一个短摘要把"任务全貌"钉在开头,详细写作要求仍放在后面的骨架里。
    titles_for_outline = _parse_section_titles(structure)
    outline_txt = "、".join(titles_for_outline[:12])
    task_outline = (
        "【任务】请基于下方【本期真实数据】撰写一份业务分析报告。\n"
        f"  必须且只能写这几章(标题逐字一致,不要增删改名):{outline_txt}\n"
        "  每章都要有:结论 → 数据支撑 → 原因分析 → 行动建议,并按段落换行。"
    ) if titles_for_outline else ""

    # ===== 【2026-10 重要修订】段落顺序:任务概要 + 数据在最前,规则在最后 =====
    #
    # 【实测踩坑】原顺序是「硬约束 → … → 白名单 → 指标数据」(数据在 1.2 万字符处),
    #   换成 MiniMax-M3.1-Flash 后模型直接写道:
    #       "当前消息仅呈现输出规范,未附可核验的经营指标原值…
    #        为避免将'100至300字'等格式参数误作业务数据,本节不虚构业绩数字"
    #   ——它把**写作规范当成了输入数据**,把章节清单字数当成了业务数字。
    #   根因:小模型对长上下文的注意力呈衰减分布,**越靠后的内容越容易被忽略**。
    #   数据是本次任务的事实基础,必须占据模型注意力的黄金位置(开头)。
    #
    # 【新顺序】任务概要 → 数据/白名单 → 章节骨架与背景 → 输出格式约束 → 硬约束
    #   这样模型开头就同时知道"要做成什么样 + 依据什么数据",
    #   不会把规则误当数据,也不会因为清单在远处而交白卷。
    parts = [
        # —— 第一梯队:任务概要 + 事实(模型最先看到的必须是"任务 + 数据")——
        task_outline,
        f"【本期真实数据】\n{indicator_text}",
        whitelist_part,
        kpi_guide_part,
        sheets_part,
        # —— 第二梯队:要做什么 ——
        body,
        background_part,
        intent_part,
        feedback_part,
        # —— 第三梯队:怎么输出 ——
        _OUTPUT_SCHEMA_HINT,
        _HARD_RULES_PREAMBLE,
        f"【参考业务资料】\n{reference}",
    ]
    # 过滤空段(业务背景/本次重点/用户意见/数据来源为空时仅留实际非空段,行为兼容旧实现)
    parts = [p for p in parts if p]
    return "\n\n".join(parts)


def _render_sheet_source(sheets: list[dict[str, Any]] | None) -> str:
    """构造【数据来源】小节:Excel 含 ≥2 张 sheet 时,告诉 LLM 数据跨多张表。

    仅在 `len(sheets) > 1` 时返回非空字符串;否则返回空串(让上层 filter 掉)。
    单 sheet / CSV 场景完全保持旧行为,避免在原本就简单的数据上制造噪声。
    """
    if not sheets or len(sheets) <= 1:
        return ""
    # 用 "name(行数)" 形式逐张列出,中文逗号分隔;上限 12 张防止超 token
    # （典型台账就 2~6 张,超长截断即可）
    head_sheets = sheets[:12]
    items = "、".join(
        f"{s.get('name', '?')}({s.get('rows', 0)} 行,{s.get('cols', 0)} 列)"
        for s in head_sheets
    )
    more = "" if len(sheets) <= 12 else f"等共 {len(sheets)} 张"
    return (
        f"【数据来源】\n本数据来自 {len(head_sheets)}{more}工作表:{items}。"
        "【本期真实数据】中的每一行均带 `_sheet_name` 字段标识来源,"
        "**请主动引用各 sheet 的数字**(如:渠道维度的数据看 sheet「渠道分析」、"
        "产品维度的看 sheet「产品分析」、目标完成率对照看 sheet「目标设定」),"
        "不要只盯着第一个 sheet 的明细数据;跨 sheet 数字冲突以合计/平均列的 sheet 为准。"
    )
